import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const tokenFiles = [
  "design-tokens/mobile.primitives.tokens.json",
  "design-tokens/mobile.semantic.tokens.json",
  "design-tokens/mobile.component.tokens.json",
];
const outputPath = join(
  repoRoot,
  "ios/SideStage/Sources/Generated/SideStageTokens.swift",
);

function flattenTokens(node, prefix = [], output = new Map()) {
  if (node && typeof node === "object" && "$value" in node) {
    output.set(prefix.join("."), node.$value);
    return output;
  }

  if (!node || typeof node !== "object" || Array.isArray(node)) {
    return output;
  }

  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$") || key === "_meta") continue;
    flattenTokens(value, [...prefix, key], output);
  }
  return output;
}

function resolveToken(name, tokens, resolving = []) {
  if (!tokens.has(name)) throw new Error(`Unknown token reference: ${name}`);
  if (resolving.includes(name)) {
    throw new Error(
      `Circular token reference: ${[...resolving, name].join(" -> ")}`,
    );
  }

  const value = tokens.get(name);
  const match =
    typeof value === "string" ? value.match(/^\{([^}]+)\}$/) : null;
  return match
    ? resolveToken(match[1], tokens, [...resolving, name])
    : value;
}

function swiftName(value) {
  const [first, ...rest] = value.split("-");
  return [
    first,
    ...rest.map((part) => part.charAt(0).toUpperCase() + part.slice(1)),
  ].join("");
}

const tokens = new Map();
for (const tokenFile of tokenFiles) {
  const payload = JSON.parse(readFileSync(join(repoRoot, tokenFile), "utf8"));
  for (const [name, value] of flattenTokens(payload)) {
    tokens.set(name, value);
  }
}

const semanticColors = [
  "background",
  "surface",
  "surface-raised",
  "stage",
  "border",
  "text",
  "text-muted",
  "text-faint",
  "accent",
  "accent-strong",
  "violet",
  "warning",
  "success",
  "danger",
];
const componentColors = [
  "primary-button-background",
  "primary-button-text",
  "live-indicator",
  "auction-leader",
  "bid-warning",
];

function colorLines(names) {
  return names
    .map((name) => {
      const value = resolveToken(`color.${name}`, tokens);
      if (
        typeof value !== "string" ||
        !/^#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?$/.test(value)
      ) {
        throw new Error(
          `Expected a hex color for color.${name}, got ${JSON.stringify(value)}`,
        );
      }
      return `        static let ${swiftName(name)} = SwiftUI.Color(hex: "${value.toUpperCase()}")`;
    })
    .join("\n");
}

const minimumTouchTarget = resolveToken(
  "size.minimum-touch-target",
  tokens,
);
const minimumTouchPoints = Number(
  String(minimumTouchTarget).replace(/px$/, ""),
);
if (!Number.isFinite(minimumTouchPoints)) {
  throw new Error(
    `Expected size.minimum-touch-target in px, got ${JSON.stringify(minimumTouchTarget)}`,
  );
}

const generated = `// SPDX-License-Identifier: MIT
// Generated by tools/build-scripts/generate-swift-design-tokens.mjs. Do not edit.

import SwiftUI

enum SideStageTokens {
    enum Semantic {
${colorLines(semanticColors)}
    }

    enum Component {
${colorLines(componentColors)}
        static let minimumTouchTarget: CGFloat = ${minimumTouchPoints}
    }
}

private extension SwiftUI.Color {
    init(hex: String) {
        let value = UInt64(hex.dropFirst(), radix: 16) ?? 0
        let hasAlpha = hex.count == 9
        let red = Double((value >> (hasAlpha ? 24 : 16)) & 0xFF) / 255
        let green = Double((value >> (hasAlpha ? 16 : 8)) & 0xFF) / 255
        let blue = Double((value >> (hasAlpha ? 8 : 0)) & 0xFF) / 255
        let alpha = hasAlpha ? Double(value & 0xFF) / 255 : 1
        self.init(.sRGB, red: red, green: green, blue: blue, opacity: alpha)
    }
}
`;

const relativeOutput = relative(repoRoot, outputPath);
if (process.argv.includes("--check")) {
  if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== generated) {
    throw new Error(`ERROR: ${relativeOutput} is stale; regenerate it`);
  }
  console.log("✓ Swift design tokens are current");
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated);
  console.log(`✓ Generated ${relativeOutput}`);
}
